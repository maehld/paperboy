#!/usr/bin/env python3
"""Build docs/logo/preview.html from the SVG files next to it.

The page embeds the marks inline instead of linking them, so it renders wherever the file
is opened from - a browser on the checkout, a copy in a temp directory, an editor preview.
Run it again after changing one of the SVGs:  python3 build-preview.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).parent
FILES = ["paperboy.svg", "paperboy-small.svg", "paperboy-square.svg", "paperboy-lockup.svg"]


def inline(name: str) -> str:
    """Return the SVG without the XML prolog, the title and its fixed width and height."""
    svg = (HERE / name).read_text()
    svg = re.sub(r"^<\?xml[^>]*\?>\s*", "", svg)
    svg = re.sub(r"<!DOCTYPE[^>]*>\s*", "", svg)
    svg = re.sub(r"<title>.*?</title>\s*", "", svg, flags=re.S)
    svg = re.sub(r'\s(width|height)="\d+"', "", svg, count=2)
    return re.sub(r"^<svg ", "<svg ", svg).strip()


TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="color-scheme" content="light">
<title>Paperboy logo</title>
<!-- Generated by build-preview.py from the SVG files in this directory: edit those, not this. -->
<style>
  :root {{ color-scheme: light; }}
  body {{ margin: 0; padding: 40px; font: 14px ui-monospace, Menlo, Consolas, monospace; background: #f4f4f2; color: #111; }}
  h1 {{ font-size: 15px; font-weight: 600; letter-spacing: .08em; text-transform: uppercase; color: #666; margin: 0; }}
  h2 {{ font-size: 13px; font-weight: 600; text-transform: uppercase; letter-spacing: .08em; color: #666; margin: 36px 0 8px; }}
  p.note {{ color: #777; margin: 4px 0 0; font-size: 12px; }}
  .row {{ display: flex; gap: 40px; align-items: flex-end; flex-wrap: wrap; background: #fff; padding: 28px; border: 1px solid #ddd; margin-top: 8px; }}
  .row.dark {{ background: #111; border-color: #111; }}
  .row.dark svg {{ filter: invert(1); }}
  .cell {{ text-align: center; color: #888; font-size: 11px; }}
  .cell svg {{ display: block; margin: 0 auto 10px; height: auto; }}
  .s16 svg {{ width: 16px; }}
  .s24 svg {{ width: 24px; }}
  .s32 svg {{ width: 32px; }}
  .s48 svg {{ width: 48px; }}
  .s96 svg {{ width: 96px; }}
  .s160 svg {{ width: 160px; }}
  .s192 svg {{ width: 192px; }}
  .s452 svg {{ width: 452px; }}
</style>
</head>
<body>
  <h1>Paperboy — logo</h1>

  <h2>paperboy.svg — the mark</h2>
  <p class="note">A page divided into four by three cells of 16 units, one cell drawn by a widget, the top-right corner turned down. Use from 32 px.</p>
  <div class="row">
    <div class="cell s32">{mark32}<span>32</span></div>
    <div class="cell s48">{mark48}<span>48</span></div>
    <div class="cell s96">{mark96}<span>96</span></div>
    <div class="cell s192">{mark192}<span>192</span></div>
  </div>

  <h2>paperboy-small.svg — 16 to 24 px</h2>
  <p class="note">The dividers are dropped and the frame thickens, so the mark keeps its weight in a favicon.</p>
  <div class="row">
    <div class="cell s16">{small16}<span>16</span></div>
    <div class="cell s24">{small24}<span>24</span></div>
    <div class="cell s32">{small32}<span>32</span></div>
    <div class="cell s48">{small48}<span>48</span></div>
  </div>

  <h2>paperboy-square.svg — avatar, repository, container image</h2>
  <div class="row">
    <div class="cell s32">{square32}<span>32</span></div>
    <div class="cell s96">{square96}<span>96</span></div>
    <div class="cell s160">{square160}<span>160</span></div>
  </div>

  <h2>paperboy-lockup.svg — mark and wordmark</h2>
  <p class="note">The wordmark is Go Mono Bold as outlines, the font family Paperboy draws text displays with.</p>
  <div class="row">
    <div class="cell s452">{lockup}<span>452</span></div>
  </div>

  <h2>Inverted</h2>
  <p class="note">The shapes are one colour and transparent, so they work on dark surfaces too.</p>
  <div class="row dark">
    <div class="cell s48">{mark48}<span>48</span></div>
    <div class="cell s96">{mark96}<span>96</span></div>
    <div class="cell s452">{lockup}<span>452</span></div>
  </div>
</body>
</html>
"""


def main() -> None:
    svgs = {name: inline(name) for name in FILES}
    mark, small, square, lockup = (svgs[n] for n in FILES)
    html = TEMPLATE.format(
        mark32=mark, mark48=mark, mark96=mark, mark192=mark,
        small16=small, small24=small, small32=small, small48=small,
        square32=square, square96=square, square160=square,
        lockup=lockup,
    )
    (HERE / "preview.html").write_text(html)
    print(f"wrote {(HERE / 'preview.html')} ({len(html)} bytes)")


if __name__ == "__main__":
    main()
